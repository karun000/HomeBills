// The calendar table's 2081–2083 rows align with Nepal's published New Year
// dates when the 1978 anchor is 1921-04-12. This keeps current dates accurate
// (for example, 2024-04-13 is 2081-01-01).
const START_AD = Date.UTC(1921, 3, 12);
const MIN_YEAR = 1978;

const pad = (value: number) => String(value).padStart(2, '0');
const daysInYear = (year: number) => {
  const months = MONTH_DAYS[year];
  if (!months) throw new Error(`Unsupported BS year: ${year}`);
  return months.reduce((sum, days) => sum + days, 0);
};

export type BsDate = { year: number; month: number; day: number };

export function parseBs(value: string): BsDate {
  const match = /^(\d{4})-(\d{1,2})-(\d{1,2})$/.exec(value.trim());
  if (!match) throw new Error('Use date format YYYY-MM-DD.');
  const year = Number(match[1]); const month = Number(match[2]); const day = Number(match[3]);
  const monthDays = MONTH_DAYS[year]?.[month - 1];
  if (!monthDays || day < 1 || day > monthDays) throw new Error('Invalid Nepali date.');
  return { year, month, day };
}

export function bsToAd(value: string): Date {
  const { year, month, day } = parseBs(value);
  let offset = day - 1;
  for (let y = MIN_YEAR; y < year; y += 1) offset += daysInYear(y);
  for (let m = 1; m < month; m += 1) offset += MONTH_DAYS[year][m - 1];
  return new Date(START_AD + offset * 86400000);
}

export function adToBs(value: Date | string = new Date()): string {
  const date = typeof value === 'string' ? new Date(`${value.slice(0, 10)}T00:00:00Z`) : value;
  let offset = Math.floor((Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) - START_AD) / 86400000);
  if (offset < 0) throw new Error('Date is outside the supported BS range.');
  let year = MIN_YEAR;
  while (offset >= daysInYear(year)) { offset -= daysInYear(year); year += 1; }
  let month = 1;
  while (offset >= MONTH_DAYS[year][month - 1]) { offset -= MONTH_DAYS[year][month - 1]; month += 1; }
  return `${year}-${pad(month)}-${pad(offset + 1)}`;
}

export const todayBs = () => adToBs(new Date());
